DIST = runtime.dist_path("ios")
COMMON = runtime.native_common()
TEMPLATE = Path(__file__).resolve().parent.parent / "templates" / "ios"
WRAP_SCRIPT = Path(__file__).resolve().parent / "ios_wrap.py"

STDLIB_SKIP = ("test", "idlelib", "tkinter", "turtledemo", "ensurepip", "lib2to3", "config-3.13")
# kind -> pip platform tag. "catalyst" is the native Mac desktop app (UIKit on macOS); there is no Catalyst wheel tag,
# so it takes macOS wheels (pure-Python packages work; binary ones must not depend on AppKit-only APIs).
PIP_TAGS = {"simulator": "ios_15_0_arm64_iphonesimulator", "device": "ios_15_0_arm64_iphoneos",
            "catalyst": "macosx_11_0_arm64"}
KINDS = tuple(PIP_TAGS)


def tool_path(name: str) -> str:
    p = shutil.which(name)
    if not p:
        raise BuildError("%s not found on PATH" % name)
    return p


def find_slice(kind: str) -> Optional[Path]:
    """kind: 'simulator', 'device' or 'catalyst'. Returns the xcframework slice dir, or None if not built."""
    xc = DIST / "Python.xcframework"
    if not xc.is_dir():
        return None
    for d in sorted(xc.iterdir()):
        if d.is_dir() and d.name.startswith("ios-") and _slice_kind(d.name) == kind:
            return d
    return None


def _slice_kind(name: str) -> str:
    if name.endswith("maccatalyst"):
        return "catalyst"
    return "simulator" if name.endswith("simulator") else "device"


GEN = "pyxpo-gen"
NATIVE_FILES = ("pyxpo_bridge.c", "pyxpo_bridge.h", "pyxpo_layout.c", "pyxpo_layout.h")


def native_dir(project: Path) -> Path:
    """The ejected `ios/` folder when `pyxpo prebuild` made one, else a throwaway one under build/."""
    ejected = Path(project) / "ios"
    return ejected if prebuild_mod.is_ejected(ejected) else Path(project) / "build" / "ios" / "shell"


def xcconfig_text(nc: Dict[str, object], has_entitlements: bool = False, extra: Optional[Dict[str, str]] = None) -> str:
    """Build settings driven by `[tool.pyxpo]`; project.yml includes this file and must not override these keys."""
    lines = [
        "// Generated by pyxpo on every build. Edit [tool.pyxpo] in pyproject.toml instead.",
        "PRODUCT_BUNDLE_IDENTIFIER = %s" % nc["ios"]["bundle_id"],
        "PRODUCT_NAME = %s" % nc["product_name"],
        "PYXPO_DISPLAY_NAME = %s" % nc["name"],
        "MARKETING_VERSION = %s" % nc["version"],
        "CURRENT_PROJECT_VERSION = %s" % nc["ios"]["build_number"],
        "PYXPO_SCHEME = %s" % nc["scheme"],
        "PYXPO_PYTHON = %s" % sys.executable,  # runs `-m pyxpo stage ios` when Xcode builds an ejected project
    ] + ios_config.xcconfig_lines(nc, has_entitlements, extra)
    if nc["team_id"]:
        lines.append("DEVELOPMENT_TEAM = %s" % nc["team_id"])
    base = '"$(inherited)" "$(PROJECT_DIR)/%s/runtime" "$(PROJECT_DIR)/%s/native"' % (GEN, GEN)
    lines.append("HEADER_SEARCH_PATHS = " + base)
    for kind, sdk in (("simulator", "iphonesimulator*"), ("device", "iphoneos*"), ("catalyst", "macosx*")):
        sl = find_slice(kind)
        if sl is not None:
            lines.append('HEADER_SEARCH_PATHS[sdk=%s] = %s "$(PROJECT_DIR)/%s/Python.xcframework/%s/Python.framework/Headers"'
                         % (sdk, base, GEN, sl.name))
    if find_slice("catalyst") is not None:  # the native Mac desktop app (`pyxpo run desktop`)
        lines += ["SUPPORTS_MACCATALYST = YES", "SUPPORTS_MAC_DESIGNED_FOR_IPHONE_IPAD = NO",
                  "PYXPO_DEVICE_FAMILY[sdk=macosx*] = 1,2,6", "DERIVE_MACCATALYST_PRODUCT_BUNDLE_IDENTIFIER = NO"]
    return "\n".join(lines) + "\n"


def render_gen(native: Path, nc: Dict[str, object], linked: Optional[autolink.Linked] = None, project: Optional[Path] = None) -> Path:
    """Refreshes the framework-owned `pyxpo-gen/` folder. Never touches anything outside it.
    Files are rendered into a scratch folder, then synced, so an Xcode build already running keeps its inputs."""
    runtime.ensure("ios", path=DIST)
    final = native / GEN
    gen = native / (GEN + ".tmp")
    if gen.exists():
        shutil.rmtree(str(gen))
    gen.mkdir(parents=True)
    for rel, data in prebuild_mod.render(TEMPLATE / "gen", {}).items():
        out = gen / rel
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_bytes(data)
        if out.suffix == ".sh":
            out.chmod(0o755)
    shutil.copy2(str(WRAP_SCRIPT), str(gen / "scripts" / "ios_wrap.py"))
    (gen / "native").mkdir()
    for f in NATIVE_FILES:
        shutil.copy2(str(COMMON / f), str(gen / "native" / f))
    (gen / "Python.xcframework").symlink_to(DIST / "Python.xcframework")
    mods, opts = (linked.modules, linked.options) if linked else ([], {})
    # Module usage-description keys go through INFOPLIST_KEY_* (Xcode merges them into App/Info.plist); a build-phase edit is overwritten.
    pmods = config_plugins.load(nc, project)
    xc = xcconfig_text(nc, ios_config.write(gen, native, nc, pmods), pmods.apply_xcconfig({})) + "".join("INFOPLIST_KEY_%s = %s\n" % (k, v.replace("//", "/$()/").replace("\r", " ").replace("\n", " "))
                                    for k, v in sorted(autolink.info_plist(mods, opts).items()))
    (gen / "Pyxpo.xcconfig").write_text(xc)
    autolink.render_ios(gen, mods, opts)
    if project is not None:
        icons.ios(project, nc, gen)
        splash.ios(project, nc, gen)
        pmods.run_dangerous("ios", project, native)
    prebuild_mod.sync_tree(gen, final, keep=("stage",))  # stage/ is filled by stage()
    return final


def prebuild(project: Path, clean: bool = False) -> Path:
    """Ejects `<project>/ios`: user-owned files are written once (edited ones are kept), `pyxpo-gen/` is refreshed."""
    project = Path(project).resolve()
    cfg = load_config(project)
    nc = native_config.resolve(cfg, project)
    linked = autolink.link(cfg, project)
    dest = project / "ios"
    if clean and dest.exists():
        shutil.rmtree(str(dest))
    rendered = prebuild_mod.render(TEMPLATE / "user", {})
    rendered[".gitignore"] = ("%s/\n%s.tmp/\n*.xcodeproj/\n*.pyxpo-new\n" % (GEN, GEN)).encode()
    from .. import __version__
    actions = prebuild_mod.apply(rendered, dest, __version__)
    for action, rel in actions:
        if action == "conflict":
            term.warn("kept your edited ios/%s; new version saved as ios/%s.pyxpo-new" % (rel, rel))
    render_gen(dest, nc, linked, project)
    if shutil.which("xcodegen"):  # so `open ios/PyxpoApp.xcodeproj` works right away, as after `expo prebuild`
        _run(["xcodegen", "generate", "--spec", dest / "project.yml", "--project", dest], cwd=str(dest), quiet=True)
    else:
        term.warn("xcodegen not found: run `brew install xcodegen`, then `pyxpo prebuild ios` to create ios/PyxpoApp.xcodeproj")
    return dest


def stage_project(project: Path, release: bool = False, kind: str = "simulator") -> None:
    """`pyxpo stage ios`: what an Xcode build of an ejected project runs before compiling."""
    project = Path(project).resolve()
    stage(native_dir(project), project, load_config(project), release, kind)


def stage(native: Path, project: Path, cfg: Dict[str, object], release: bool, kind: str) -> None:
    """Refreshes pyxpo-gen/ (config, runtime, Python, app, site-packages). User-owned files stay untouched."""
    runtime.ensure("ios", path=DIST)
    slice_dir = find_slice(kind)
    if slice_dir is None:
        raise BuildError("no iOS %s CPython in %s (device builds need an ios-arm64 slice in the runtime; "
                         "set PYXPO_IOS_DIST or see `pyxpo doctor`)" % (kind, DIST))
    nc = native_config.resolve(cfg, project)
    if prebuild_mod.is_ejected(native):
        autolink.check_ios_wiring(native)
    linked = autolink.link(cfg, project)
    gen = render_gen(native, nc, linked, project)
    st = gen / "stage"
    _stage_stdlib(slice_dir, st / ("python-" + kind), host_python())
    _stage_app(project, st / "app_root", release, linked.modules)
    app_json.write(st / "app_root" / "pyxpo", nc)
    install_requires(list(cfg.get("requires", [])), kind, st / ("site-" + kind), pip_index_args(cfg, project))


def install_requires(requires: List[str], kind: str, target: Path, index_args: List[str] = ()) -> None:
    if target.exists():
        shutil.rmtree(str(target))
    target.mkdir(parents=True)
    if not requires:
        return
    _run([sys.executable, "-m", "pip", "install", "--target", target, "--platform", PIP_TAGS[kind],
          "--python-version", "3.13", "--implementation", "cp", "--only-binary=:all:", "--no-compile"] + list(index_args) + requires)


def host_python() -> Optional[Path]:
    """A CPython 3.13 interpreter for compiling the stdlib to .pyc, when the runtime does not ship them."""
    cands = [os.environ.get("PYXPO_HOST_PYTHON"), sys.executable if sys.version_info[:2] == (3, 13) else None,
             shutil.which("python3.13")]
    if runtime.is_dev_checkout():
        cands.append(str(runtime.REPO / ".cache" / "Python-3.13.7" / "cross-build" / "build" / "python.exe"))
    for c in cands:
        if c and Path(c).is_file():
            return Path(c)
    return None


def _stage_stdlib(slice_dir: Path, dest: Path, compile_with: Optional[Path]) -> None:
    if dest.exists():
        shutil.rmtree(str(dest))
    src = slice_dir / "lib" / "python3.13"
    shutil.copytree(str(src), str(dest / "lib" / "python3.13"), symlinks=True,
                    ignore=lambda d, names: [n for n in names if n in STDLIB_SKIP])
    shipped_pyc = any((dest / "lib" / "python3.13" / "__pycache__").glob("os.*.pyc"))
    if not shipped_pyc and compile_with and compile_with.is_file():  # read-only bundle: ship .pyc so startup is fast
        subprocess.run([str(compile_with), "-m", "compileall", "-q", "-j0", str(dest / "lib" / "python3.13")],
                       check=False, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)


def _stage_app(project: Path, dest: Path, release: bool, modules: Optional[List[autolink.Module]] = None) -> None:
    if dest.exists():
        shutil.rmtree(str(dest))
    for sub in ("app", "assets"):
        d = project / sub
        if d.is_dir():
            shutil.copytree(str(d), str(dest / sub), ignore=shutil.ignore_patterns("__pycache__", ".*"))
    pkg = Path(__file__).resolve().parent.parent
    for p in sorted(pkg.rglob("*.py")):
        rel = p.relative_to(pkg)
        if _skip_runtime_file(rel, release):
            continue
        out = dest / "pyxpo" / rel
        out.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(str(p), str(out))
    for src, arc in autolink.python_files(modules or []):  # linked module packages live outside pyxpo
        out = dest / arc
        out.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(str(src), str(out))


# -- simulator ------------------------------------------------------------
def pick_simulator(devices_json: dict) -> Optional[Dict[str, str]]:
    """Choose a simulator from `simctl list devices available -j`: booted iPhone, else newest iPhone."""
    cands = []
    for runtime, devs in devices_json.get("devices", {}).items():
        if "iOS" not in runtime:
            continue
        for d in devs:
            if d.get("isAvailable", True) and d.get("name", "").startswith("iPhone"):
                cands.append((d.get("state") == "Booted", runtime, d["name"], d))
    if not cands:
        return None
    cands.sort(key=lambda c: (c[0], c[1], c[2]))
    return cands[-1][3]


def simulator() -> Dict[str, str]:
    out = subprocess.run(["xcrun", "simctl", "list", "devices", "available", "-j"],
                         check=True, capture_output=True, text=True).stdout
    dev = pick_simulator(json.loads(out))
    if dev is None:
        raise BuildError("no iPhone simulator found; install one in Xcode")
    if dev.get("state") != "Booted":
        _run(["xcrun", "simctl", "boot", dev["udid"]])
    # Show the Simulator window when the app exists; a headless simulator is fine without it.
    if subprocess.run(["open", "-Ra", "Simulator"], capture_output=True).returncode == 0:
        subprocess.run(["open", "-a", "Simulator"], check=False)
    return dev


def launch_env(extras: Optional[Dict[str, str]]) -> Dict[str, str]:
    """simctl forwards variables prefixed SIMCTL_CHILD_ to the app (prefix stripped)."""
    env = dict(os.environ)
    for k, v in (extras or {}).items():
        env["SIMCTL_CHILD_" + k] = v
    return env


def launch(udid: str, app_id: str, extras: Optional[Dict[str, str]] = None, console: bool = True) -> "subprocess.Popen":
    cmd = ["xcrun", "simctl", "launch"] + (["--console-pty"] if console else []) + [
        "--terminate-running-process", udid, app_id]
    print("> " + " ".join(cmd))
    return subprocess.Popen(cmd, env=launch_env(extras))


# -- build ----------------------------------------------------------------
def build(project: Path, release: bool = False, kind: str = "simulator") -> Path:
    project = Path(project).resolve()
    cfg = load_config(project)
    nc = native_config.resolve(cfg, project)
    tool_path("xcodegen")
    native = native_dir(project)
    if not prebuild_mod.is_ejected(native):  # implicit prebuild: a disposable project nobody edits
        if native.exists():
            shutil.rmtree(str(native))
        rendered = prebuild_mod.render(TEMPLATE / "user", {})
        for rel, data in rendered.items():
            (native / rel).parent.mkdir(parents=True, exist_ok=True)
            (native / rel).write_bytes(data)
    stage(native, project, cfg, release, kind)

    _run(["xcodegen", "generate", "--spec", native / "project.yml", "--project", native], cwd=str(native))
    cfgname = "Release" if release else "Debug"
    derived = project / "build" / "ios" / "DerivedData"
    cmd = ["xcodebuild", "-project", native / "PyxpoApp.xcodeproj", "-scheme", "PyxpoApp",
           "-configuration", cfgname, "-derivedDataPath", derived]
    if kind == "catalyst":
        products = "%s-maccatalyst" % cfgname
        cmd += ["-destination", "platform=macOS,variant=Mac Catalyst,arch=arm64", "build"]
        if not nc["team_id"]:  # xcodegen's target presets beat the xcconfig, so sign to run locally from here
            cmd += ["CODE_SIGN_IDENTITY=-", "CODE_SIGN_STYLE=Manual", "DEVELOPMENT_TEAM="]
    else:
        sdk = "iphonesimulator" if kind == "simulator" else "iphoneos"
        products = "%s-%s" % (cfgname, sdk)
        cmd += ["-sdk", sdk, "build"]
        if kind == "simulator":
            cmd += ["ARCHS=arm64", "ONLY_ACTIVE_ARCH=YES"]
    _run(cmd, env=dict(os.environ, PYXPO_STAGED="1"))
    app = derived / "Build" / "Products" / products / ("%s.app" % nc["product_name"])
    if not app.is_dir():
        raise BuildError("app not produced: %s" % app)
    print("built %s" % app)
    return app


class MacApp:
    """The Catalyst app, started through LaunchServices (`open`) so macOS treats it as its own app: privacy prompts
    (Photos, camera) belong to the app, not to the terminal that ran pyxpo. Its output goes to a log file that a thread
    copies to this terminal. Same wait()/terminate() calls as a Popen."""

    def __init__(self, app: Path, extras: Optional[Dict[str, str]] = None) -> None:
        self.exe = app / "Contents" / "MacOS" / app.stem
        # launchd opens the log for the app; a path on an external volume makes the launch fail (-10810).
        self.log = Path(tempfile.mkdtemp(prefix="pyxpo-mac-")) / (app.stem + ".log")
        self.log.write_bytes(b"")
        env = {k: v for k, v in os.environ.items() if k.startswith("PYXPO_")}
        env.update(extras or {}, PYXPO_STDIO="1")
        args = ["open", "-n", "-W", "--stdout", str(self.log), "--stderr", str(self.log)]
        for k, v in sorted(env.items()):
            args += ["--env", "%s=%s" % (k, v)]
        print("> open " + str(app))
        self.proc = subprocess.Popen(args + [str(app)])
        threading.Thread(target=self._echo, daemon=True, name="pyxpo-mac-log").start()

    def _echo(self) -> None:
        with open(self.log, "rb") as f:
            while True:
                chunk = f.read()
                if chunk:
                    sys.stdout.buffer.write(chunk)
                    sys.stdout.flush()
                elif self.proc.poll() is not None:
                    return
                else:
                    time.sleep(0.2)

    def wait(self) -> int:
        return self.proc.wait()

    def terminate(self) -> None:
        if self.proc.poll() is None:
            subprocess.run(["pkill", "-f", str(self.exe)], check=False)
            self.proc.terminate()


def run_mac(app: Path, extras: Optional[Dict[str, str]] = None) -> MacApp:
    return MacApp(app, extras)


def install_and_run(app: Path, app_id: str, extras: Optional[Dict[str, str]] = None) -> "subprocess.Popen":
    dev = simulator()
    _run(["xcrun", "simctl", "install", dev["udid"], app])
    return launch(dev["udid"], app_id, extras)
